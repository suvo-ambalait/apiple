  // Local HTML escaper (does not depend on core's esc, quotes included).
  function escHtml(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  // Remove everything from the line starting with "**cURL**" onward
  // (code snippets are generated by snippets.js instead).
  function stripCurl(md) {
    var lines = String(md || '').split(/\r?\n/);
    for (var i = 0; i < lines.length; i++) {
      if (/^\s*\*\*cURL\*\*/.test(lines[i])) { lines = lines.slice(0, i); break; }
    }
    return lines.join('\n').replace(/\s+$/, '');
  }

  // Pretty-print example values (objects, or JSON strings) for display.
  function pretty(v) {
    if (v == null) return '';
    if (typeof v === 'string') {
      try { return JSON.stringify(JSON.parse(v), null, 2); } catch (e) { return v; }
    }
    try { return JSON.stringify(v, null, 2); } catch (e) { return String(v); }
  }

  function fmtVal(v) {
    return (v !== null && typeof v === 'object') ? JSON.stringify(v) : String(v);
  }

  function hasVal(v) { return v !== undefined && v !== null && v !== ''; }

  /* ------------------------------------------------------------------ *
   * Tiny, safe markdown renderer. Escapes HTML FIRST, then applies a
   * small set of patterns, so raw tags can never reach the DOM.
   * ------------------------------------------------------------------ */

  function inlineMd(text) {
    var s = escHtml(text);
    var codes = [];
    // Protect inline code so other rules don't touch its content.
    s = s.replace(/`([^`\n]+)`/g, function (_, c) {
      codes.push('<code>' + c + '</code>');
      return '\u0000' + (codes.length - 1) + '\u0000';
    });
    // Links: javascript:/data:/vbscript: are dropped (entities decoded first).
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, function (_, label, url) {
      if (/^\s*(javascript|data|vbscript):/i.test(url.replace(/&#\d+;|&#x[0-9a-f]+;/gi, ''))) return label;
      return '<a href="' + url + '" target="_blank" rel="noopener">' + label + '</a>';
    });
    s = s.replace(/\*\*([^*\n]+)\*\*/g, '<strong>$1</strong>');
    s = s.replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, '$1<em>$2</em>');
    s = s.replace(/\u0000(\d+)\u0000/g, function (_, i) { return codes[+i]; });
    return s;
  }

  function renderMarkdown(src) {
    var lines = String(src == null ? '' : src).replace(/\r\n?/g, '\n').split('\n');
    var out = [], para = [], list = null, i = 0;

    function flushPara() {
      if (para.length) { out.push('<p>' + inlineMd(para.join(' ')) + '</p>'); para = []; }
    }
    function flushList() {
      if (list) {
        out.push('<' + list.tag + '>' + list.items.map(function (t) {
          return '<li>' + inlineMd(t) + '</li>';
        }).join('') + '</' + list.tag + '>');
        list = null;
      }
    }

    while (i < lines.length) {
      var line = lines[i], m;
      if (/^\s*```/.test(line)) {                       // fenced code block
        flushPara(); flushList();
        var buf = [];
        i++;
        while (i < lines.length && !/^\s*```/.test(lines[i])) { buf.push(lines[i]); i++; }
        i++; // skip closing fence (or end of input)
        out.push('<pre class="code-block"><code>' + escHtml(buf.join('\n')) + '</code></pre>');
        continue;
      }
      if (/^\s*$/.test(line)) { flushPara(); flushList(); i++; continue; }
      if ((m = /^\s*[-*]\s+(.*)$/.exec(line))) {          // bullet list
        flushPara();
        if (!list || list.tag !== 'ul') { flushList(); list = { tag: 'ul', items: [] }; }
        list.items.push(m[1]); i++; continue;
      }
      if ((m = /^\s*\d+[.)]\s+(.*)$/.exec(line))) {      // numbered list
        flushPara();
        if (!list || list.tag !== 'ol') { flushList(); list = { tag: 'ol', items: [] }; }
        list.items.push(m[1]); i++; continue;
      }
      flushList();
      para.push(line.trim());
      i++;
    }
    flushPara(); flushList();
    return out.join('\n');
  }
  A.renderMarkdown = renderMarkdown;

