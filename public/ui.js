  // URL bar text: muted base URL + path with {params} highlighted.
  function fillUrlText(code, op) {
    code.innerHTML = '';
    var path = el('span', { class: 'url-path' });
    String(op.path).split(/(\{[^}]+\})/).forEach(function (part) {
      if (!part) return;
      path.appendChild(/^\{[^}]+\}$/.test(part) ? el('span', { class: 'url-param' }, part) : document.createTextNode(part));
    });
    code.appendChild(el('span', { class: 'url-base' }, getBaseUrl()));
    code.appendChild(path);
  }

  function responsesCard(list) {
    var firstOk = -1;
    list.forEach(function (r, i) { if (firstOk < 0 && /^2/.test(String(r.status))) firstOk = i; });
    var wrap = el('div', { class: 'resp-list' });
    list.forEach(function (r, i) {
      var hasBody = hasVal(r.example);
      var row = el('div', { class: 'resp' + (i === firstOk ? ' open' : '') });
      var head = el('button', { class: 'resp-head', type: 'button',
        onclick: function () { row.classList.toggle('open'); } },
        el('span', { class: 'status ' + statusClass(r.status) }, String(r.status)),
        el('span', { class: 'resp-desc' }, r.description || ''),
        el('span', { class: 'chev' }));
      row.appendChild(head);
      row.appendChild(el('div', { class: 'resp-body' },
        hasBody ? codeWrap(pretty(r.example)) : el('p', { class: 'muted' }, 'No response body.')));
      wrap.appendChild(row);
    });
    return card('Responses', list.length, wrap);
  }

  function renderOp(op) {
    var page = el('div', { class: 'op-page' });

    // Breadcrumbs
    page.appendChild(el('nav', { class: 'crumbs' },
      el('a', { href: '#/' }, 'API'), el('span', { class: 'sep' }, '/'),
      el('span', {}, op.tag), el('span', { class: 'sep' }, '/'),
      el('span', { class: 'current' }, op.summary || op.path)));

    var layout = el('div', { class: 'op-layout' });
    var docs = el('section', { class: 'op-docs' });
    layout.appendChild(docs);
    page.appendChild(layout);

    // 1. Header: title + badges
    var badges = el('div', { class: 'op-badges' },
      op.auth ? el('span', { class: 'badge badge-auth' }, '🔒 Needs token')
              : el('span', { class: 'badge badge-public' }, 'Public'));
    if (op.deprecated) badges.appendChild(el('span', { class: 'badge' }, 'Deprecated'));
    docs.appendChild(el('header', { class: 'op-header' },
      el('h1', { class: 'op-title' }, op.summary || op.path), badges));

    // 2. URL bar: where the request goes
    var urlCode = el('code', { class: 'url-text' });
    fillUrlText(urlCode, op);
    docs.appendChild(el('div', { class: 'urlbar' },
      badge(op.method, true), urlCode,
      el('button', { class: 'copy-btn', type: 'button',
        onclick: function () { A.copy(getBaseUrl() + op.path); } }, 'Copy')));
    urlRefresh = function () { fillUrlText(urlCode, op); };

    // 3. Description (cURL part stripped) + auth callout
    var desc = stripCurl(op.description);
    if (desc) docs.appendChild(el('div', { class: 'op-desc', html: renderMarkdown(desc) }));
    if (op.auth) {
      docs.appendChild(el('div', { class: 'callout callout-auth' },
        'This endpoint needs a Bearer token (',
        el('code', {}, 'Authorization: Bearer <token>'), '). ',
        el('button', { class: 'btn btn-small open-settings', type: 'button', onclick: openSettings }, 'Open Settings')));
    }

    // 4. Parameter cards (path / query / headers)
    [['path', 'Path parameters'], ['query', 'Query parameters'], ['header', 'Headers']].forEach(function (g) {
      var list = (op.params || []).filter(function (p) { return p['in'] === g[0]; });
      if (!list.length) return;
      docs.appendChild(card(g[1], list.length, el('div', { class: 'field-list' }, list.map(fieldRow))));
    });

    // 5. Request body
    if (op.body) {
      var b = op.body;
      var sub = el('div', { class: 'card-sub' }, 'Content-Type: ', el('code', {}, b.contentType || 'application/json'),
        b.required ? ' · ' : null, b.required ? el('span', { class: 'tag-required' }, 'required') : null);
      var bodyCard = card('Request body', (b.fields && b.fields.length) ? b.fields.length : null, sub);
      if (/multipart\/form-data/i.test(b.contentType || '')) {
        bodyCard.appendChild(el('p', { class: 'hint' }, 'Send as multipart/form-data; file fields are sent as files.'));
      }
      if (b.fields && b.fields.length) bodyCard.appendChild(el('div', { class: 'field-list' }, b.fields.map(fieldRow)));
      if (hasVal(b.example)) bodyCard.appendChild(codeWrap(pretty(b.example)));
      docs.appendChild(bodyCard);
    }

    // 6. Responses accordion
    if (op.responses && op.responses.length) docs.appendChild(responsesCard(op.responses));

    // 7. Try it panel (tryit.js is optional)
    var slot = el('div', { class: 'tryit-slot' });
    layout.appendChild(el('aside', { class: 'op-side' }, slot));
    if (typeof A.mountTryIt === 'function') {
      try { A.mountTryIt(op, slot); }
      catch (e) { slot.appendChild(el('p', { class: 'muted' }, 'Try it is unavailable: ' + (e && e.message || e))); }
    } else {
      slot.appendChild(el('p', { class: 'muted' }, 'Try it is unavailable.'));
    }

    setContent(page, (op.summary || op.path) + ' · ' + SITE);
    setActive(op.id);
    revealGroup(op.tag);
  }

