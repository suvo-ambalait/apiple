  function setContent(node, title) {
    contentEl.innerHTML = '';
    contentEl.appendChild(node);
    contentEl.scrollTop = 0;
    try { window.scrollTo(0, 0); } catch (e) { /* ignore */ }
    document.title = title;
  }

  function getBaseUrl() {
    var b = '';
    try { b = (A.settings && A.settings.get('baseUrl')) || ''; } catch (e) { /* no storage */ }
    return String(b).replace(/\/+$/, '');
  }

