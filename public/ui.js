  // <div.code-wrap><pre.code-block/><button.copy-btn/></div>
  function codeWrap(text) {
    var btn = el('button', {
      class: 'copy-btn', type: 'button',
      onclick: function () { A.copy(text); }
    }, 'Copy');
    return el('div', { class: 'code-wrap' }, el('pre', { class: 'code-block' }, text), btn);
  }

  function badge(method, large) {
    return el('span', { class: 'badge-method ' + (large ? 'lg ' : '') + A.methodClass(method) },
      String(method || '').toUpperCase());
  }

  function statusClass(status) {
    var c = String(status).charAt(0);
    return /[2-5]/.test(c) ? 's' + c + 'xx' : '';
  }

  // <section.card><h2.card-title>Title <span.count>n</span></h2> ...children
  function card(title, count) {
    var c = el('section', { class: 'card' },
      el('h2', { class: 'card-title' }, title, count != null ? ' ' : null,
        count != null ? el('span', { class: 'count' }, String(count)) : null));
    for (var i = 2; i < arguments.length; i++) if (arguments[i]) c.appendChild(arguments[i]);
    return c;
  }

  function typeText(o) {
    return (o.type || 'string') + (o.format ? ' (' + o.format + ')' : '') + (o.nullable ? ', nullable' : '');
  }

  // One `.field` row for a parameter or body field (never a table).
  function fieldRow(o) {
    var head = el('div', { class: 'field-head' },
      el('span', { class: 'field-name' }, o.name),
      el('span', { class: 'field-type' }, typeText(o)),
      o.required ? el('span', { class: 'tag-required' }, 'required')
                 : el('span', { class: 'tag-optional' }, 'optional'));
    var row = el('div', { class: 'field' }, head);
    if (o.description) row.appendChild(el('div', { class: 'field-desc', html: renderMarkdown(o.description) }));

    var chips = [];
    if (o.constraints) {
      (Array.isArray(o.constraints) ? o.constraints : String(o.constraints).split(/,\s*/)).forEach(function (c) {
        if (c) chips.push(el('span', { class: 'chip' }, c));
      });
    }
    if (o.enum && o.enum.length) chips.push(el('span', { class: 'chip chip-enum' }, 'enum: ' + o.enum.map(fmtVal).join(' | ')));
    if (hasVal(o['default'])) chips.push(el('span', { class: 'chip chip-default' }, 'default: ' + fmtVal(o['default'])));
    // Only scalar examples as chips (object examples are shown in the example block).
    if (hasVal(o.example) && typeof o.example !== 'object') chips.push(el('span', { class: 'chip chip-example' }, 'example: ' + fmtVal(o.example)));
    if (chips.length) row.appendChild(el('div', { class: 'field-meta' }, chips));
    return row;
  }

